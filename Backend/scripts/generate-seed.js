// Generates supabase/seed.sql (demonstration data only) from scripts/seed-data.js.
// Each item gets an "Opening" movement so that stock equals the sum of its movement ledger,
// followed by the sample history movements in chronological order.
//   node scripts/generate-seed.js
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SEED_PRODUCTS, SEED_MOVEMENTS } from './seed-data.js';

const OUT = fileURLToPath(new URL('../../supabase/seed.sql', import.meta.url));
const OPENING_AT = '2026-10-01 08:00:00+08';
const TZ = '+08'; // sample history timestamps are Philippine local time

const q = v => v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const lines = [];
const out = s => lines.push(s);

out('-- DEMONSTRATION DATA ONLY. Generated by Backend/scripts/generate-seed.js; do not edit by hand.');
out('-- Product names are real product lines, but prices, stock, sales rates, lead times and performance');
out('-- indices are illustrative sample values, not live inventory, market pricing, or benchmarks.');
out('-- Apply to an empty database after the migrations (supabase db reset, or npm run db:seed).');
out('begin;');
out("select set_config('unitworks.stock_change', 'on', true);");
out('');

out('insert into inventory_items (id, sku, category_key, brand, name, price, unit_cost, stock, min_stock, daily_sales, lead_time_days, moq, perf_gaming, perf_work, perf_score) values');
out(SEED_PRODUCTS.map(p => `  (${[p.id, p.sku, p.category, p.brand, p.name, p.price, p.cost, p.stock, p.minStock, p.dailySales, p.leadTime, p.moq,
  p.perf.gaming ?? null, p.perf.work ?? null, p.perf.score ?? null].map(q).join(', ')})`).join(',\n') + ';');
out('');

const specRows = [];
for (const p of SEED_PRODUCTS) {
  for (const [k, v] of Object.entries(p.specs)) {
    if (v === null || v === undefined || v === '') continue; // unknown spec: no row
    specRows.push(`  (${[p.id, p.category, k, String(v)].map(q).join(', ')})`);
  }
}
out('insert into component_specs (item_id, category_key, spec_key, value) values');
out(specRows.join(',\n') + ';');
out('');

// Ledger: opening balance + history, with running stock_after
const history = SEED_MOVEMENTS.slice().sort((a, b) => a.date.localeCompare(b.date));
const movements = [];
for (const p of SEED_PRODUCTS) {
  const opening = p.stock - history.filter(m => m.productId === p.id).reduce((s, m) => s + m.qty, 0);
  if (opening < 0) throw new Error(`Seed history for ${p.id} implies negative opening stock`);
  if (opening > 0) movements.push({ at: OPENING_AT, id: p.id, type: 'Opening', qty: opening, note: 'Opening balance (demo data)', user: 'system' });
}
for (const m of history) movements.push({ at: m.date.replace('T', ' ') + ':00' + TZ, id: m.productId, type: m.type, qty: m.qty, note: m.note, user: m.user });
const running = {};
out('insert into inventory_movements (item_id, movement_type, quantity, stock_after, note, performed_by, created_at) values');
out(movements.map(m => {
  running[m.id] = (running[m.id] || 0) + m.qty;
  if (running[m.id] < 0) throw new Error(`Seed ledger for ${m.id} goes negative`);
  return `  (${[m.id, m.type, m.qty, running[m.id], m.note, m.user, m.at].map(q).join(', ')})`;
}).join(',\n') + ';');
out('');
out("select set_config('unitworks.stock_change', 'off', true);");
out('commit;');

writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`Wrote ${OUT}: ${SEED_PRODUCTS.length} items, ${specRows.length} spec values, ${movements.length} movements`);
